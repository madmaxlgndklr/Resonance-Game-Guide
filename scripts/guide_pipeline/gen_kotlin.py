"""Generate Kotlin @Serializable data classes from the pydantic schema.

    python3 scripts/guide_pipeline/gen_kotlin.py

Emitting the Kotlin from the same models that validate the JSON means the two
cannot drift: change schema.py, re-run this, and the app's models follow.
"""

from __future__ import annotations

import datetime as dt
import types
import typing
from pathlib import Path

from pydantic import BaseModel
from pydantic.fields import FieldInfo

import schema

REPO_ROOT = Path(__file__).resolve().parents[2]
PACKAGE = "com.madmaxlgndklr.resonanceguide.data.model"
OUTPUT = (
    REPO_ROOT
    / "app/src/main/java/com/madmaxlgndklr/resonanceguide/data/model/GuideModels.kt"
)

SCALARS = {
    str: "String",
    int: "Int",
    float: "Double",
    bool: "Boolean",
}

#: Models emitted, in dependency order so the file reads top-down.
ORDER = [
    schema.Coverage,
    schema.SourceRecord,
    schema.Meta,
    schema.Mechanic,
    schema.Objective,
    schema.Chapter,
    schema.Hero,
    schema.VisionSkill,
    schema.Vision,
    schema.Esper,
    schema.SideQuest,
    schema.CaveMaster,
    schema.ColosseumBattle,
    schema.ColosseumLeague,
    schema.ChamberTrial,
    schema.Adamantite,
    schema.LootEntry,
    schema.Equipment,
    schema.Item,
    schema.Enemy,
    schema.TabletShard,
    schema.OblivionTier,
    schema.Collectibles,
    schema.DialogueChoice,
    schema.Asset,
    schema.AssetsManifest,
    schema.Guide,
]


def kotlin_type(annotation: typing.Any) -> tuple[str, bool]:
    """Return the Kotlin type for ``annotation`` and whether it is nullable."""
    origin = typing.get_origin(annotation)

    if origin in (typing.Union, types.UnionType):
        args = [a for a in typing.get_args(annotation) if a is not type(None)]
        nullable = len(args) != len(typing.get_args(annotation))
        if len(args) == 1:
            inner, _ = kotlin_type(args[0])
            return inner, nullable
        # int | None style unions beyond one real type: fall back to String.
        return "String", nullable

    if origin is list:
        (item,) = typing.get_args(annotation) or (str,)
        inner, inner_null = kotlin_type(item)
        return f"List<{inner}{'?' if inner_null else ''}>", False

    if origin is dict:
        args = typing.get_args(annotation) or (str, str)
        key, _ = kotlin_type(args[0])
        value, value_null = kotlin_type(args[1])
        return f"Map<{key}, {value}{'?' if value_null else ''}>", False

    if isinstance(annotation, type):
        if annotation in SCALARS:
            return SCALARS[annotation], False
        if issubclass(annotation, BaseModel):
            return annotation.__name__, False
        if annotation in (dt.date, dt.datetime):
            return "String", False

    if typing.get_origin(annotation) is typing.Literal:
        return "String", False

    return "String", False


def default_for(kotlin: str, nullable: bool, info: FieldInfo) -> str | None:
    if nullable:
        return "null"
    if kotlin.startswith("List<"):
        return "emptyList()"
    if kotlin.startswith("Map<"):
        return "emptyMap()"
    if info.default_factory is not None:
        try:
            produced = info.default_factory()
        except TypeError:
            return None
        if isinstance(produced, BaseModel):
            return f"{type(produced).__name__}()"
    return None


def render(model: type[BaseModel]) -> str:
    lines = ["@Serializable", f"data class {model.__name__}("]
    for name, info in model.model_fields.items():
        kotlin, nullable = kotlin_type(info.annotation)
        # `def` is a Kotlin keyword only as a name clash risk; the JSON key is
        # kept via @SerialName so the data file stays unchanged.
        serial_name = info.alias or name
        property_name = "defense" if serial_name == "def" else name
        annotation = (
            f'    @SerialName("{serial_name}") '
            if serial_name != property_name
            else "    "
        )
        default = default_for(kotlin, nullable, info)
        suffix = f" = {default}" if default is not None else ""
        lines.append(
            f"{annotation}val {property_name}: {kotlin}{'?' if nullable else ''}{suffix},"
        )
    lines.append(")")
    return "\n".join(lines)


def main() -> int:
    body = "\n\n".join(render(model) for model in ORDER)
    header = f"""// Generated by scripts/guide_pipeline/gen_kotlin.py -- do not edit by hand.
// Regenerate after changing scripts/guide_pipeline/schema.py:
//     python3 scripts/guide_pipeline/gen_kotlin.py
//
// These mirror app/src/main/assets/ff_resonance_guide.json exactly. Unknown
// keys are ignored by the Json configuration in GuideDataSource, so adding a
// field to the data file will not crash an older build.

package {PACKAGE}

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

"""
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(header + body + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} ({len(ORDER)} data classes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
