package com.madmaxlgndklr.resonanceguide.data.model

import android.content.Context
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.decodeFromStream

/**
 * Reads the bundled guide dataset out of `assets/`.
 *
 * The file is about a megabyte, so parsing happens on [Dispatchers.IO] and the
 * result is cached for the process lifetime: callers get the same [Guide]
 * instance rather than re-parsing per screen.
 */
class GuideDataSource(private val context: Context) {

    private val json = Json {
        // The data file is regenerated by scripts/guide_pipeline and may gain
        // fields ahead of the app. Ignoring unknown keys keeps an older build
        // working against a newer dataset instead of throwing at startup.
        ignoreUnknownKeys = true
        explicitNulls = false
    }

    @Volatile
    private var cached: Guide? = null

    suspend fun load(): Guide {
        cached?.let { return it }
        return withContext(Dispatchers.IO) {
            synchronized(this@GuideDataSource) {
                cached ?: parse().also { cached = it }
            }
        }
    }

    private fun parse(): Guide =
        context.assets.open(ASSET_NAME).use { stream ->
            @OptIn(kotlinx.serialization.ExperimentalSerializationApi::class)
            json.decodeFromStream<Guide>(stream)
        }

    companion object {
        const val ASSET_NAME = "ff_resonance_guide.json"
    }
}
