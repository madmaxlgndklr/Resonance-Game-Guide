package com.madmaxlgndklr.resonanceguide.data.local

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.TypeConverters
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

@Database(
    entities = [
        ChapterEntity::class,
        ObjectiveEntity::class,
        WalkthroughAreaEntity::class,
        DialogueChoiceEntity::class,
        SideQuestEntity::class,
        EnemyEntity::class,
        OptionalBossEntity::class,
        VisionEntity::class,
        VisionSkillEntity::class,
        EquipmentEntity::class,
        ItemEntity::class,
        TabletShardEntity::class,
        OblivionTierEntity::class,
        ProgressEntity::class,
    ],
    version = 3,
    exportSchema = true,
)
@TypeConverters(Converters::class)
abstract class GuideDatabase : RoomDatabase() {
    abstract fun guideDao(): GuideDao
    abstract fun progressDao(): ProgressDao

    companion object {
        private const val NAME = "resonance_guide.db"

        /**
         * Version 1 keyed every table by an autogenerated `Int`, including
         * `progress.entityId`. Version 2 keys everything by the dataset's own
         * stable string ids so that checklist state survives content updates.
         *
         * An integer id from version 1 cannot be mapped onto a string id --
         * `5` told us nothing about which record it was, only its position in
         * a hand-written list that no longer exists -- so this migration drops
         * the version 1 tables, `progress` included, and recreates the version
         * 2 schema empty for the seeder to repopulate from the asset. Version
         * 1 was never released, so the only state lost is from pre-release
         * test installs.
         *
         * A migration has to leave the schema exactly as Room expects it:
         * Room creates tables only when a database is first created, never on
         * an upgrade path, so dropping without recreating would leave the
         * database with no tables at all. [GuideSchemaV2] therefore holds the
         * `createSql` of every entity and index in
         * `app/schemas/...GuideDatabase/2.json`, verbatim, and
         * `GuideSchemaV2Test` fails if the two drift apart.
         *
         * Future migrations must preserve `progress`. That is the whole point
         * of moving to stable ids, and is why this database has no
         * `fallbackToDestructiveMigration`.
         */
        // internal rather than private so MigrationTest can hand it to
        // MigrationTestHelper: that helper takes the migrations to apply as an
        // argument and finds no path without them.
        internal val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                for (table in OLD_TABLES) {
                    db.execSQL("DROP TABLE IF EXISTS `$table`")
                }
                for (statement in GuideSchemaV2.STATEMENTS) {
                    db.execSQL(statement)
                }
            }
        }

        /**
         * Version 3 adds `walkthrough_areas` and `dialogue_choices`: the
         * area-by-area walkthrough notes and the stat-bonus conversations.
         *
         * Purely additive, so unlike [MIGRATION_1_2] this drops nothing. Both
         * tables are new and empty afterwards; [GuideSeeder] fills them on the
         * next launch, because the dataset version in the asset moved at the
         * same time. `progress` is untouched, so every existing check-off
         * survives -- the thing [MIGRATION_1_2] gave up and the reason this
         * database has no `fallbackToDestructiveMigration`.
         *
         * The DDL is the `createSql` of each entity and index as Room exports
         * it to `app/schemas/...GuideDatabase/3.json`, verbatim. Room
         * validates the result against that file on the upgrade path, so a
         * character out of place fails at runtime; `GuideSchemaV3Test` checks
         * the two against each other at build time instead.
         */
        internal val MIGRATION_2_3 = object : Migration(2, 3) {
            override fun migrate(db: SupportSQLiteDatabase) {
                for (statement in GuideSchemaV3.ADDED_STATEMENTS) {
                    db.execSQL(statement)
                }
            }
        }

        private val OLD_TABLES = listOf(
            "chapters",
            "quests",
            "quest_steps",
            "bosses",
            "items",
            "character_builds",
            "progress",
        )

        fun build(context: Context): GuideDatabase =
            Room.databaseBuilder(context.applicationContext, GuideDatabase::class.java, NAME)
                // A version 1 database upgrades along 1 -> 2 -> 3: the first
                // migration recreates the version 2 schema, the second adds
                // the version 3 tables on top.
                .addMigrations(MIGRATION_1_2, MIGRATION_2_3)
                .build()
    }
}
