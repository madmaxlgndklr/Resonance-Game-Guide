package com.madmaxlgndklr.resonanceguide.data

import com.madmaxlgndklr.resonanceguide.data.local.GuideSchemaV2
import java.io.File
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Checks `GuideSchemaV2.STATEMENTS` against the exported schema.
 *
 * `MIGRATION_1_2` recreates the database from that list, and Room validates
 * the result against `2.json` on every upgrade. If the two drift, the
 * migration throws on a user's device. This keeps that a build failure.
 *
 * A JVM test rather than an instrumented one, so it runs on every
 * `./gradlew test` without an emulator.
 */
class GuideSchemaV2Test {

    private val schemaFile = File(
        "schemas/com.madmaxlgndklr.resonanceguide.data.local.GuideDatabase/2.json",
    )

    /** Tables then their indices, in the order Room emits them. */
    private fun expectedStatements(): List<String> {
        assertTrue(
            "exported schema not found at ${schemaFile.absolutePath}; " +
                "build the app once to export it",
            schemaFile.isFile,
        )
        val database = Json.parseToJsonElement(schemaFile.readText())
            .jsonObject.getValue("database").jsonObject

        return buildList {
            database.getValue("entities").jsonArray.forEach { element ->
                val entity = element.jsonObject
                val table = entity.getValue("tableName").jsonPrimitive.content
                fun substitute(sql: String) = sql.replace("\${TABLE_NAME}", table)

                add(substitute(entity.getValue("createSql").jsonPrimitive.content))
                entity["indices"]?.jsonArray?.forEach { index ->
                    add(
                        substitute(
                            index.jsonObject.getValue("createSql").jsonPrimitive.content,
                        ),
                    )
                }
            }
        }
    }

    @Test
    fun `migration DDL matches the exported version 2 schema`() {
        val expected = expectedStatements()
        val actual = GuideSchemaV2.STATEMENTS

        // Compare as lists so the failure names the first statement that
        // differs rather than just reporting a size mismatch.
        assertEquals(
            "GuideSchemaV2.STATEMENTS is out of step with 2.json. Regenerate it " +
                "from the exported schema; do not hand-edit.",
            expected,
            actual,
        )
    }

    @Test
    fun `every version 2 table is created by the migration`() {
        val created = GuideSchemaV2.STATEMENTS
            .mapNotNull { Regex("CREATE TABLE IF NOT EXISTS `([^`]+)`").find(it)?.groupValues?.get(1) }
            .toSet()

        val expected = setOf(
            "chapters",
            "objectives",
            "side_quests",
            "enemies",
            "optional_bosses",
            "visions",
            "vision_skills",
            "equipment",
            "items",
            "tablet_shards",
            "oblivion_tiers",
            "progress",
        )
        assertEquals(expected, created)
    }

    @Test
    fun `progress survives as a string-keyed table`() {
        val progress = GuideSchemaV2.STATEMENTS
            .single { it.startsWith("CREATE TABLE IF NOT EXISTS `progress`") }

        // The whole point of schema 2: checklist state keyed by the dataset's
        // string ids rather than an autogenerated integer.
        assertTrue(
            "progress.entityId must be TEXT, was: $progress",
            progress.contains("`entityId` TEXT NOT NULL"),
        )
        assertTrue(progress.contains("PRIMARY KEY(`type`, `entityId`)"))
    }
}
