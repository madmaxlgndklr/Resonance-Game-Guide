// High-resolution maps and sprites are kept outside the repo (they are large
// and not ours to redistribute). Whatever lives in this directory is merged
// into the APK's assets, so `maps/chapter_01.webp` on disk is loaded by Coil
// as `file:///android_asset/maps/chapter_01.webp`.
val guideAssetsDir: String = providers.gradleProperty("resonance.assetsDir")
    .orElse("/home/madmaxlgndklr/Git/Resonance-Assets")
    .get()

